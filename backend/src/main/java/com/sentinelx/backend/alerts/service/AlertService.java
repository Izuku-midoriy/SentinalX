package com.sentinelx.backend.alerts.service;

import com.sentinelx.backend.alerts.dto.AlertResponse;
import com.sentinelx.backend.alerts.entity.Alert;
import com.sentinelx.backend.alerts.model.AlertStatus;
import com.sentinelx.backend.alerts.repository.AlertRepository;
import com.sentinelx.backend.audit.model.AuditOutcome;
import com.sentinelx.backend.audit.service.AuditService;
import com.sentinelx.backend.detection.engine.AlertCandidate;
import com.sentinelx.backend.tenancy.context.TenantContext;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

@Service
public class AlertService {

    private static final Logger log = LoggerFactory.getLogger(AlertService.class);

    private final AlertRepository alertRepository;
    private final AuditService auditService;
    private final com.sentinelx.backend.operations.metrics.SentinelXMetrics metrics;

    public AlertService(AlertRepository alertRepository, AuditService auditService, com.sentinelx.backend.operations.metrics.SentinelXMetrics metrics) {
        this.alertRepository = alertRepository;
        this.auditService = auditService;
        this.metrics = metrics;
    }

    @Transactional
    public Alert createOrUpdateAlert(UUID tenantId, AlertCandidate candidate) {
        // Deduplication: look for active alert with same deduplication key
        Optional<Alert> existingOpt = alertRepository.findByTenantIdAndDeduplicationKeyAndStatusIn(
                tenantId,
                candidate.deduplicationKey(),
                List.of(AlertStatus.OPEN, AlertStatus.INVESTIGATING)
        );

        if (existingOpt.isPresent()) {
            Alert existing = existingOpt.get();
            existing.setLastSeenAt(candidate.timestamp());
            existing.setEventCount(existing.getEventCount() + 1);

            // Add any newly observed supporting event IDs
            for (UUID eventId : candidate.supportingEventIds()) {
                boolean alreadyLinked = existing.getEvents().stream()
                        .anyMatch(ae -> ae.getEventId().equals(eventId));
                if (!alreadyLinked) {
                    existing.addEvent(eventId);
                }
            }

            Alert updated = alertRepository.save(existing);
            log.info("Deduplicated alert updated: id={}, dedupKey={}, totalEvents={}",
                    updated.getId(), updated.getDeduplicationKey(), updated.getEventCount());
            return updated;
        }

        // New alert creation
        Alert newAlert = new Alert(
                tenantId,
                candidate.ruleKey(),
                candidate.ruleVersion(),
                candidate.title(),
                candidate.description(),
                candidate.severity(),
                candidate.confidence(),
                candidate.deduplicationKey(),
                candidate.timestamp()
        );

        for (UUID eventId : candidate.supportingEventIds()) {
            newAlert.addEvent(eventId);
        }

        Alert saved = alertRepository.save(newAlert);
        metrics.recordAlertGenerated(saved.getRuleKey(), saved.getSeverity());
        log.warn("ALERT GENERATED: id={}, rule={}, severity={}, tenant={}",
                saved.getId(), saved.getRuleKey(), saved.getSeverity(), tenantId);

        auditService.record(
                tenantId,
                null,
                "SYSTEM/DETECTION_ENGINE",
                "ALERT_CREATED",
                "ALERT",
                saved.getId().toString(),
                AuditOutcome.SUCCESS,
                "Alert generated by rule " + candidate.ruleKey() + " v" + candidate.ruleVersion(),
                "127.0.0.1"
        );

        return saved;
    }

    @Transactional(readOnly = true)
    public Page<AlertResponse> searchAlerts(String severity, AlertStatus status, Pageable pageable) {
        UUID tenantId = TenantContext.requireTenantId();
        String normSeverity = severity != null && !severity.isBlank() ? severity.toUpperCase().trim() : null;

        return alertRepository.searchAlerts(tenantId, normSeverity, status, pageable)
                .map(AlertResponse::fromEntity);
    }

    @Transactional(readOnly = true)
    public AlertResponse getAlertById(UUID alertId) {
        UUID tenantId = TenantContext.requireTenantId();
        Alert alert = alertRepository.findByTenantIdAndIdWithEvents(tenantId, alertId)
                .orElseThrow(() -> new IllegalArgumentException("Alert not found with ID: " + alertId));
        return AlertResponse.fromEntity(alert);
    }

    @Transactional
    public AlertResponse updateAlert(UUID alertId, AlertStatus newStatus, UUID assignedTo) {
        UUID tenantId = TenantContext.requireTenantId();
        Alert alert = alertRepository.findByTenantIdAndIdWithEvents(tenantId, alertId)
                .orElseThrow(() -> new IllegalArgumentException("Alert not found with ID: " + alertId));

        if (newStatus != null) {
            alert.setStatus(newStatus);
        }
        if (assignedTo != null) {
            alert.setAssignedTo(assignedTo);
        }

        Alert saved = alertRepository.save(alert);

        auditService.record(
                tenantId,
                TenantContext.getUserId(),
                TenantContext.get() != null ? TenantContext.get().email() : "UNKNOWN",
                "ALERT_UPDATED",
                "ALERT",
                saved.getId().toString(),
                AuditOutcome.SUCCESS,
                "Alert status changed to " + saved.getStatus(),
                "127.0.0.1"
        );

        return AlertResponse.fromEntity(saved);
    }
}
